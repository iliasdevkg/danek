import { clsx, type ClassValue } from "clsx";
import { extendTailwindMerge } from "tailwind-merge";

/**
 * tailwind-merge обучен нашей типографической шкале.
 *
 * Без этого он не отличал `text-body` (размер) от `text-accent-fg` (цвет):
 * обе утилиты попадали в группу «цвет текста», побеждала последняя, и белая
 * подпись основной кнопки молча превращалась в чёрную — 1.4:1 вместо 12:1.
 * Регистрация шкалы разводит их по разным группам.
 *
 * ВАЖНО: добавили имя размера в globals.css — допишите его сюда в том же
 * коммите. Иначе `cn("text-app-sm", "text-ink-muted")` снова сочтёт размер
 * цветом, цвет победит, и вернётся ровно тот баг контраста, ради которого
 * этот список и заведён.
 *
 * Две шкалы живут рядом намеренно. Первая — витрины, текучая: заголовок обязан
 * расти вместе с окном, потому что на обложке он и есть картинка. Вторая —
 * приложения, фиксированная: CRM читают на одном комфортном кегле независимо
 * от того, ноутбук это или двадцатисемидюймовый монитор, и таблица, набранная
 * на них по-разному, теряет выверенную плотность.
 */
const twMerge = extendTailwindMerge({
  extend: {
    classGroups: {
      "font-size": [
        {
          text: [
            // Витрина — текучая шкала.
            "display",
            "h1",
            "h2",
            "h3",
            "lead",
            "body",
            "small",
            "caption",
            "kicker",
            // Админка — фиксированная шкала.
            "app",
            "app-xs",
            "app-sm",
            "app-label",
            "app-heading",
            "app-title",
            "app-metric",
            "app-metric-lg",
          ],
        },
      ],
    },
  },
});

/**
 * Склейка классов с разрешением конфликтов Tailwind:
 * последний класс той же группы выигрывает, поэтому проп `className`
 * у компонента всегда может переопределить его собственные стили.
 */
export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}
